// Writes emissions.gen.ts: every emission the state vectors of an `endpoint` or a `relay` expect (the §12 engine's;
// `authority` and `subscriber` traces drive dsip-broadcast), typed as the hand-written `Emission` declaration
// in dsip-wasm (`src/types.rs`), so `tsc` checks the declaration against the contract rather than the implementation.
// Run from web/: node test/types/emissions.mjs && npx tsc -p .
//
// Spec: none (infrastructure). The shape is the vectors README's (kind `state`).
import { readdir, readFile, writeFile } from 'node:fs/promises';

const dir = new URL('../../../vectors/state/', import.meta.url);
const out = [];
const walk = (x, name) => {
  if (Array.isArray(x)) x.forEach((y) => walk(y, name));
  else if (x && typeof x === 'object') {
    for (const [k, v] of Object.entries(x)) {
      if (k === 'emit' && Array.isArray(v)) for (const e of v) out.push(`  ${JSON.stringify(e)}, // ${name}`);
      else walk(v, name);
    }
  }
};
for (const f of (await readdir(dir)).filter((f) => f.endsWith('.json')).sort()) {
  const v = JSON.parse(await readFile(new URL(f, dir), 'utf8'));
  if (['endpoint', 'relay'].includes(v.context?.component)) walk(v, f);
}
await writeFile(new URL('./emissions.gen.ts', import.meta.url),
  `// Generated by emissions.mjs from impl/vectors/state: do not edit.\nimport type { Emission } from '../../pkg/dsip_wasm.js';\n\nexport const emissions: Emission[] = [\n${out.join('\n')}\n];\n`);
console.log(`${out.length} emissions`);
