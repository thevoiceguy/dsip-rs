// Writes vectors.gen.ts: the values the vectors expect in the shapes dsip-wasm declares by hand (`src/types.rs`),
// typed as those declarations, so `tsc` checks each declaration against the contract rather than the implementation:
// every emission and every session and contacts snapshot the state vectors of an `endpoint` or a `relay` expect
// (the §12 engine's; `authority` and `subscriber` traces drive dsip-broadcast), and every verdict of the envelope,
// payload and semantic vectors.
// Run from web/: node test/types/vectors.mjs && npx tsc -p .
//
// Spec: none (infrastructure). The shapes are the vectors README's (kinds `state`, `envelope`, `payload`, `semantic`).
import { readdir, readFile, writeFile } from 'node:fs/promises';

const vectors = new URL('../../../vectors/', import.meta.url);
const found = { emissions: [], sessions: [], contacts: [], verdicts: [] };
const walk = (x, name) => {
  if (Array.isArray(x)) x.forEach((y) => walk(y, name));
  else if (x && typeof x === 'object') {
    for (const [k, v] of Object.entries(x)) {
      if (k === 'emit' && Array.isArray(v)) for (const e of v) found.emissions.push(`  ${JSON.stringify(e)}, // ${name}`);
      else if (k === 'sessions' || k === 'contacts') found[k].push(`  ${JSON.stringify(v)}, // ${name}`);
      else walk(v, name);
    }
  }
};
const read = async (kind) => {
  const dir = new URL(`${kind}/`, vectors);
  const files = (await readdir(dir)).filter((f) => f.endsWith('.json')).sort();
  return Promise.all(files.map(async (f) => [f, JSON.parse(await readFile(new URL(f, dir), 'utf8'))]));
};
for (const [f, v] of await read('state')) if (['endpoint', 'relay'].includes(v.context?.component)) walk(v.input, f);
for (const kind of ['envelope', 'payload', 'semantic']) {
  for (const [f, v] of await read(kind)) found.verdicts.push(`  ${JSON.stringify(v.expect)}, // ${kind}/${f}`);
}
const list = (name, type) => `export const ${name}: ${type}[] = [\n${found[name].join('\n')}\n];\n`;
await writeFile(new URL('./vectors.gen.ts', import.meta.url),
  `// Generated by vectors.mjs from impl/vectors: do not edit.\n`
  + `import type { ContactsSnapshot, Emission, FrameVerdict, Sessions } from '../../pkg/dsip_wasm.js';\n\n`
  + list('emissions', 'Emission') + list('sessions', 'Sessions') + list('contacts', 'ContactsSnapshot') + list('verdicts', 'FrameVerdict'));
console.log(Object.entries(found).map(([k, v]) => `${v.length} ${k}`).join(', '));
